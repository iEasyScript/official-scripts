package com.projectx.script.impl.archaeology

/**
 * The collector collections, generated from the collection_* varbits: each one's "complete" bit and, per
 * artefact, the bit that records it as handed in plus the restored item that satisfies it.
 *
 * Reading these is what lets the script answer "which collection am I closest to finishing, and what do I
 * still have to dig up for it" after a restart, without having kept a note of its own.
 */

/** One artefact slot in a collection: the restored item, and the bit set once it has been handed in. */
data class CollectionSlot(val restoredId: Int, val name: String, val donatedVarbit: Int)

/**
 * Where a collector stands. A collector with no tile is one the wiki has no map pin for; the script skips
 * their collections and says so rather than wandering, because a guessed coordinate is worse than none.
 */
data class CollectorSpot(val x: Int, val y: Int, val plane: Int)

/** A single collector collection - the unit the Collectors Assemble achievements count. */
data class CollectorCollection(
    val collector: String,
    val collectorNpcId: Int,
    val where: String,
    val index: Int,
    val completeVarbit: Int,
    val spot: CollectorSpot?,
    val slots: List<CollectionSlot>,
)

