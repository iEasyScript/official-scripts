package com.projectx.script.impl.archaeology

/**
 * Every dig site, excavation hotspot, restoration recipe and collector collection, generated from the
 * game cache (dbtables arch_site, arch_excavation, arch_restoration, collection and collector, joined to
 * the arch_* varbits and to the scenery that carries an Excavate option).
 *
 * Nothing here is guessed: the levels, object ids and state varbits are the ones the game itself reads,
 * so the planner can decide where to dig and what to restore without a hand-kept list going stale.
 */

/** A dig site, as the Archaeology journal's site map lists it. [mapIndex] is its slot on that map. */
data class DigSite(val name: String, val mapIndex: Int, val level: Int, val soilId: Int)

/**
 * One excavation hotspot. [stateVarbit] is how the game itself records whether it is locked, available or
 * exhausted, which is what lets a restart resume rather than start over. [damagedArtefacts] are the damaged
 * items it yields, and [objectIds] the scenery to click.
 */
data class Hotspot(
    val name: String,
    val level: Int,
    val siteIndex: Int,
    val subSite: String,
    val subSiteLevel: Int,
    val stateVarbit: Int,
    val soilId: Int,
    val objectIds: IntArray,
    val damagedArtefacts: IntArray,
) {
    override fun equals(other: Any?) = this === other || (other is Hotspot && other.name == name && other.level == level)
    override fun hashCode() = name.hashCode() * 31 + level
}

/** A restoration recipe: the damaged artefact in, the restored artefact out, and what it pays. */
data class Restoration(val damagedId: Int, val restoredId: Int, val name: String, val level: Int, val xp: Int)

/** A collector's collection. Completing one counts towards the Collectors Assemble achievements. */
data class ArtefactCollection(val name: String, val restoredIds: IntArray)

/** An archaeological collector, and where they stand. */
data class Collector(val name: String, val npcId: Int, val where: String)

