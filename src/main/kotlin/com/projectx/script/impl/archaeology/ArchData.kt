    /** Every soil type, so a backpack filling with soil can be told apart from one filling with artefacts. */
    val soilIds: IntArray = digSites.map { it.soilId }.distinct().toIntArray()

    val damagedArtefactIds: IntArray = restorations.map { it.damagedId }.toIntArray()
    val restoredArtefactIds: IntArray = restorations.map { it.restoredId }.toIntArray()

    private val restorationByDamaged = restorations.associateBy { it.damagedId }
    private val restorationByRestored = restorations.associateBy { it.restoredId }
    private val hotspotsByDamaged: Map<Int, List<Hotspot>> =
        hotspots.flatMap { hotspot -> hotspot.damagedArtefacts.map { it to hotspot } }
            .groupBy({ it.first }, { it.second })

    fun restorationForDamaged(damagedId: Int): Restoration? = restorationByDamaged[damagedId]

    fun restorationForRestored(restoredId: Int): Restoration? = restorationByRestored[restoredId]

    fun digSite(mapIndex: Int): DigSite? = digSites.firstOrNull { it.mapIndex == mapIndex }

    /** The hotspots that yield [damagedId] - how "this collection needs that artefact" turns into somewhere to dig. */
    fun hotspotsYielding(damagedId: Int): List<Hotspot> = hotspotsByDamaged[damagedId].orEmpty()

    /**
     * Which restoration category a restored artefact is filed under, which is the dropdown the workbench
     * needs switching to before its recipe is selectable. Taken from the game's own per-category collections.
     */
    private val categoryByRestored: Map<Int, String> =
        collections.flatMap { category -> category.restoredIds.map { it to category.name } }.toMap()

    fun categoryOf(restoredId: Int): String? = categoryByRestored[restoredId]
